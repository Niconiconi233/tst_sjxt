export function defaultAuditors(): AuditorRecord[] {
  return ROWS.map(([name, department, title, qualification, capableRoles, busyProjects], i) => ({
    id: `A${1000 + i + 1}`,
    name,
    code: `SJ-${1001 + i}`,
    gender: i % 3 === 1 ? '女' : '男',
    department,
    title,
    qualification,
    phone: `138${String(10000000 + i * 1234567).slice(0, 8)}`,
    email: `user${i + 1}@audit.gov.cn`,
    capableRoles,
    busyProjects,
    avatarColor: AVATAR_COLORS[i % AVATAR_COLORS.length],
    sortOrder: i,
    enabled: true,
    builtin: true,
  }));
}
